/**
 * ボスの応答に混入しうる HTML タグを落とす純粋関数。
 *
 * **判定方式は許可リストであり、汎用正規表現（`<\/?[a-zA-Z][^>]*>`）は使わない。**
 * ボス自身がプレースホルダ記法を使う場面（例:「`<タスク名>` の形式で報告しろ」）
 * を壊すため、包含側・除外側をどちらも有限に列挙できる許可リスト方式を採る
 * （`docs/features/boss-reply-plain-text-output.md` クリティカル設計決定「判定方式:
 * 許可リスト」）。実 DB 実測で生の HTML タグは 0 件であり、この関数は症状が
 * 確認できていない事象への保険である。保険のために正当な文章を壊すのは損失が
 * 勝つ。
 *
 * タグ名の一致は**小文字のみ**（`i` フラグを使わない）。LLM が出す HTML は
 * 小文字であり、`<A>` `<B>` のような大文字のラベル表記はそのまま残す。
 *
 * 一致したタグは種別で処理を分ける。ブロック境界タグ（開始・終了・自己終了形の
 * いずれも）は改行 1 個へ、インラインタグは除去する。`white-space: pre-wrap`
 * が既に効いているため改行はそのまま反映される。
 *
 * **置換・除去以外の加工は一切しない**（トリム・連続改行の畳み込み・エンティティ
 * デコードをしない）。理由は 2 つ——(1) トリムは「応答全体でタグが 1 つでも
 * 見つかったか」という大域的な条件で発火するため、ストリーミングでは非単調に
 * なる。(2) HTML は実測で観測されておらず、空行の見た目は「タグが文字として
 * 見える」に比べて実害が小さい。
 *
 * **位置ごとの局所変換のみで構成する**。「応答全体でタグが見つかったか」の
 * ような大域的な条件で分岐しない。これにより「入力の接頭辞に対する正規化結果は、
 * 入力全体に対する正規化結果の接頭辞になる」（末尾の未確定タグを除く）という
 * 単調性が成り立ち、後続のストリーミング適用（#462）が依存する性質を満たす。
 *
 * 一致する箇所が 1 つも無い入力は 1 文字も変更せずそのまま返す（恒等）。
 *
 * **既知の限界として受け入れる**:
 * - `a<b>c` のように、`<` ＋ 単文字タグ名（このモジュールの許可リストでは
 *   `a` `b` `i` `p`）＋ `>` の形が正当な文章に現れると除去される。単文字タグを
 *   許可リストから外すと最頻出の `<p>` を取り逃すため、この形は既知の限界
 *   として受け入れる（`x < 10` や `<タスク名>` のような「`<` の直後にタグ名が
 *   続かない」形は許可リストに一致しないため保護される）。
 * - 属性値の中に文字として `>` が含まれる不正な形（例: `<a href="a>b">`）は、
 *   属性走査 `[^>\n]*` がその `>` で止まってしまい、`b">` 以降が地の文として
 *   残る。引用符を認識した属性パースは行わない（LLM がこの形の壊れた HTML
 *   属性を出す想定は薄く、対応する複雑さに見合わないため）。
 * - インラインタグの `td` `th` は表のセル区切りを再現しない（`<td>甲</td><td>乙</td>`
 *   は `甲乙` になる）。これは許可リストの分類として意図した挙動であり、表の
 *   見た目の再現は本モジュールの目的外（`docs/features/boss-reply-plain-text-output.md`
 *   の許可リスト表に従う）。
 */

/** ブロック境界タグ。一致すると改行 1 個へ置換する。 */
const BLOCK_TAG_NAMES = [
  "br",
  "p",
  "div",
  "li",
  "ul",
  "ol",
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "tr",
  "hr",
  "table",
  "blockquote",
  "pre",
] as const;

/** インラインタグ。一致すると除去する。 */
const INLINE_TAG_NAMES = [
  "strong",
  "em",
  "b",
  "i",
  "span",
  "code",
  "a",
  "td",
  "th",
] as const;

const BLOCK_TAG_NAME_SET: ReadonlySet<string> = new Set(BLOCK_TAG_NAMES);

/**
 * `<` ＋ 任意の `/` ＋ 許可リストのタグ名 ＋ 任意の属性 ＋ 任意の `/` ＋ `>`。
 *
 * タグ名の直後に否定先読み `(?![a-zA-Z0-9])` を置き、単文字タグ名（`p` `b`
 * `i` `a`）が `pre` `blockquote` のような長い他タグ名の接頭辞としてマッチし
 * 切ってしまうのを防ぐ。**この先読みは現在の属性部（`(?:[ \t][^>\n]*)?`。
 * 直後の空白がタブ／スペースのみに制限されている）と組み合わさって初めて
 * 冗長になる**——空白の代わりに任意の1文字を許すよう属性部を緩めた場合、
 * この先読みが無いと `<p1>` のような形を「`p` の一致＋残り丸ごと属性扱い」
 * として誤って許してしまう。将来この先読みを消してよいのは属性部の制約を
 * 変えないときに限る、という依存関係を明示するために残す（許可リストの
 * 列挙順が判定結果に影響しない理由も、この先読みによる）。
 *
 * 属性部 `[^>\n]*` は**改行を含めない**——`<div` のように許可リストのタグ名
 * 直後に改行が続く形が正当な文章に現れたとき、`[^>]*`（改行込み）だと次に
 * 見つかった `>` までの複数行をまとめて飲み込んでしまう（レビュー指摘）。
 * タグは常に単一行に閉じていなければならないとすることで、この飲み込みを
 * 防ぐ。LLM が出す実際の HTML タグが複数行にまたがることは想定しない。
 *
 * **状態を持つ点に注意**: `g` フラグ付きのため `lastIndex` に走査位置を持つ。
 * `String.prototype.replace` はグローバル正規表現の `lastIndex` を呼び出しの
 * たびに 0 へリセットしてから走査するため、`stripHtmlTags` の中で使う分には
 * 安全。**この定数を `test()` / `exec()` で使い回さないこと**——それらは
 * `lastIndex` を呼び出しごとに書き換えるため、同じ定数を別の場所で
 * `test()`/`exec()` に使うと呼び出し順序によって結果が変わる状態バグになる。
 */
const TAG_PATTERN = new RegExp(
  `<\\/?(${[...BLOCK_TAG_NAMES, ...INLINE_TAG_NAMES].join("|")})(?![a-zA-Z0-9])(?:[ \\t][^>\\n]*)?\\/?>`,
  "g",
);

export function stripHtmlTags(text: string): string {
  return text.replace(TAG_PATTERN, (_match, tagName: string) =>
    BLOCK_TAG_NAME_SET.has(tagName) ? "\n" : "",
  );
}
